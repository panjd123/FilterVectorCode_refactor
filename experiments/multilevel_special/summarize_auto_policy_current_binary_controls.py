#!/usr/bin/env python3
"""Summarize QF-SSL router against current-binary structural controls.

The router and all structural controls must have seven repeats generated by the
same search binary.  Repeat zero is cold; statistics use repeats 1--6.  The
script treats Recall as a hard per-repeat gate and emits both point estimates
and repeat-index bootstrap intervals for median latency ratios.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import random
import statistics
from pathlib import Path


CONTROL_LABELS = {
    "auto_mass_ladder_layer1_t1_8192": "one_layer",
    "auto_mass_ladder_t1_8192_t2_131072": "ungated_two_layer",
    "oracle_prior_t1_32000_t2_200000": "prior_tuned",
}


def percentile(values: list[float], q: float) -> float:
    ordered = sorted(values)
    position = (len(ordered) - 1) * q
    low, high = math.floor(position), math.ceil(position)
    if low == high:
        return ordered[low]
    return ordered[low] * (high - position) + ordered[high] * (position - low)


def bootstrap_ratio(
    baseline: list[float], candidate: list[float], seed: int, samples: int
) -> tuple[float, float]:
    if len(baseline) != len(candidate):
        raise ValueError("repeat counts must match")
    rng = random.Random(seed)
    ratios = []
    for _ in range(samples):
        indices = [rng.randrange(len(baseline)) for _ in baseline]
        ratios.append(
            statistics.median(baseline[index] for index in indices)
            / statistics.median(candidate[index] for index in indices)
        )
    return percentile(ratios, 0.025), percentile(ratios, 0.975)


def load_run(
    root: Path, method: str, workload: str, repeats: int, recall_target: float
) -> dict[str, object]:
    path = root / method / workload / "search_time_details.csv"
    with path.open(newline="") as stream:
        rows = list(csv.DictReader(stream))
    repeat_ids = sorted(int(row["Repeat"]) for row in rows)
    if repeat_ids != list(range(repeats)):
        raise ValueError(f"incomplete repeats {repeat_ids}: {path}")
    recalls = [float(row["Avg_Recall"]) for row in rows]
    if min(recalls) < recall_target:
        raise ValueError(
            f"Recall below {recall_target}: {method}/{workload}: {min(recalls)}"
        )
    warm = [float(row["Time_ms"]) for row in rows if int(row["Repeat"]) > 0]
    mean = statistics.mean(warm)
    return {
        "lsearch": int(rows[0]["Lsearch"]),
        "recall_min": min(recalls),
        "recall_mean": statistics.mean(recalls),
        "warm": warm,
        "median_ms": statistics.median(warm),
        "mean_ms": mean,
        "cv": statistics.stdev(warm) / mean,
        "p95_ms": percentile(warm, 0.95),
    }


def manifest_binary(root: Path, expected_runs: int) -> str:
    manifest = json.loads((root / "manifest.json").read_text())
    runs = manifest["runs"]
    if len(runs) != expected_runs:
        raise ValueError(f"expected {expected_runs} manifest runs, got {len(runs)}")
    if any(run.get("status") != "complete" or run.get("returncode") != 0 for run in runs):
        raise ValueError("control manifest contains an incomplete or failed run")
    hashes = {run["search_binary_sha256"] for run in runs}
    if len(hashes) != 1:
        raise ValueError(f"control runs used multiple binaries: {sorted(hashes)}")
    return next(iter(hashes))


def router_binary(root: Path, expected_runs: int) -> str:
    value = manifest_binary(root, expected_runs)
    return value


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("router_config", type=Path)
    parser.add_argument("control_config", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--bootstrap-samples", type=int, default=100_000)
    args = parser.parse_args()

    router_config = json.loads(args.router_config.read_text())
    control_config = json.loads(args.control_config.read_text())
    router_root = Path(router_config["output_root"])
    control_root = Path(control_config["output_root"])
    router_method = router_config["methods"][0]["name"]
    repeats = int(router_config["num_repeats"])
    if int(control_config["num_repeats"]) != repeats:
        raise ValueError("router/control repeat counts differ")
    methods = [method["name"] for method in control_config["methods"]]
    if set(methods) != set(CONTROL_LABELS):
        raise ValueError(f"unexpected control methods: {methods}")
    expected_runs = len(methods) * len(control_config["workloads"])
    binary_sha256 = manifest_binary(control_root, expected_runs)
    router_sha256 = router_binary(router_root, len(router_config["workloads"]))
    if router_sha256 != binary_sha256:
        raise ValueError(
            f"router/control binary mismatch: {router_sha256} != {binary_sha256}"
        )

    rows = []
    for workload in router_config["workloads"]:
        name = workload["name"]
        target = float(router_config["recall_thresholds"][name])
        router = load_run(router_root, router_method, name, repeats, target)
        row: dict[str, object] = {
            "workload": name,
            "mean_selectivity": workload["mean_selectivity"],
            "target_recall": target,
            "router_lsearch": router["lsearch"],
            "router_recall_min": router["recall_min"],
            "router_warm_median_ms": router["median_ms"],
            "control_binary_sha256": binary_sha256,
        }
        for method in methods:
            label = CONTROL_LABELS[method]
            control = load_run(control_root, method, name, repeats, target)
            baseline = control["warm"]
            candidate = router["warm"]
            assert isinstance(baseline, list) and isinstance(candidate, list)
            speedup = float(control["median_ms"]) / float(router["median_ms"])
            seed = int(hashlib.sha256(f"{name}:{label}:current".encode()).hexdigest()[:8], 16)
            low, high = bootstrap_ratio(
                baseline, candidate, seed, args.bootstrap_samples
            )
            row.update(
                {
                    f"{label}_lsearch": control["lsearch"],
                    f"{label}_recall_min": control["recall_min"],
                    f"{label}_warm_median_ms": control["median_ms"],
                    f"speedup_vs_{label}": speedup,
                    f"speedup_vs_{label}_ci95_low": low,
                    f"speedup_vs_{label}_ci95_high": high,
                }
            )
        rows.append(row)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
